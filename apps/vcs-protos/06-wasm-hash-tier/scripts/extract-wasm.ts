/**
 * Extracts the BLAKE3, SHA-1 and SHA-256 binaries embedded (as base64) in hash-wasm's ESM build and
 * writes them as .wasm files plus a portable base64 module for runtimes that compile from bytes.
 * Run with `pnpm extract-wasm`; R1 re-runs the extraction and compares with the committed files.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

export const ALGOS = ["blake3", "sha1", "sha256"] as const;
const require = createRequire(import.meta.url);

export function extractFromHashWasm(): { version: string; binaries: Record<string, Uint8Array> } {
  const pkgJson = require.resolve("hash-wasm/package.json");
  const version = (JSON.parse(readFileSync(pkgJson, "utf8")) as { version: string }).version;
  const src = readFileSync(join(dirname(pkgJson), "dist/index.esm.js"), "utf8");
  const binaries: Record<string, Uint8Array> = {};
  for (const algo of ALGOS) {
    const m = new RegExp(
      `var name(\\$\\w+) = "${algo}";\\s*var data\\1 = "([A-Za-z0-9+/=]+)";`,
    ).exec(src);
    if (!m?.[2]) throw new Error(`hash-wasm ${version}: no embedded binary for ${algo}`);
    binaries[algo] = new Uint8Array(Buffer.from(m[2], "base64"));
  }
  return { version, binaries };
}

const outDir = join(import.meta.dirname, "../src/wasm");

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  const { version, binaries } = extractFromHashWasm();
  const provenance: Record<string, unknown> = { source: `hash-wasm@${version}`, files: {} };
  const lines = [
    "// Generated by scripts/extract-wasm.ts from hash-wasm — do not edit.",
    "// Base64 copies of the .wasm files for runtimes that may compile from bytes (Node, browsers).",
  ];
  for (const algo of ALGOS) {
    const bytes = binaries[algo] as Uint8Array;
    writeFileSync(join(outDir, `${algo}.wasm`), bytes);
    (provenance.files as Record<string, unknown>)[`${algo}.wasm`] = {
      bytes: bytes.length,
      sha256: createHash("sha256").update(bytes).digest("hex"),
    };
    lines.push(
      `export const ${algo.toUpperCase()}_WASM_B64 = "${Buffer.from(bytes).toString("base64")}";`,
    );
  }
  writeFileSync(join(outDir, "binaries.ts"), `${lines.join("\n")}\n`);
  writeFileSync(join(outDir, "provenance.json"), `${JSON.stringify(provenance, null, 2)}\n`);
  console.log(provenance);
}
