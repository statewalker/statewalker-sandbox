// Bundles the OCR isolate (src/isolate/program.ts) into src/isolate/program.gen.js: its code as
// a string, the SHA-256 of the tesseract-core.wasm it expects and tesseract-wasm's version. The
// cell loads that code into a Worker Loader isolate with the wasm fetched from WASM_URL.
//   node scripts/build-isolate.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const dir = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(join(dir, "package.json"));

export const wasmPath = join(dir, "node_modules/tesseract-wasm/dist/tesseract-core.wasm");

export async function buildIsolate({ quiet = false } = {}) {
  const out = await esbuild.build({
    entryPoints: [join(dir, "src/isolate/program.ts")],
    bundle: true,
    format: "esm",
    platform: "neutral",
    mainFields: ["module", "main"],
    conditions: ["worker", "browser"],
    write: false,
    minify: true,
    external: ["cloudflare:workers", "./tesseract-core.wasm"],
    // See wrangler.jsonc: Emscripten's glue resolves a URL against import.meta.url at load.
    define: { "import.meta.url": JSON.stringify("file:///tesseract-do/isolate.js") },
    logLevel: "silent",
  });
  const code = out.outputFiles[0].text;
  const wasmSha256 = createHash("sha256").update(readFileSync(wasmPath)).digest("hex");
  const { version } = JSON.parse(
    readFileSync(join(dirname(require.resolve("tesseract-wasm")), "../package.json"), "utf8"),
  );
  writeFileSync(
    join(dir, "src/isolate/program.gen.js"),
    `// Generated by scripts/build-isolate.mjs: do not edit.\nexport default ${JSON.stringify({ code, wasmSha256, tesseractVersion: version })};\n`,
  );
  if (!quiet)
    console.log(
      `isolate: ${(code.length / 1024).toFixed(0)} KB of code, wasm sha256 ${wasmSha256.slice(0, 16)}…`,
    );
}

if (import.meta.url === `file://${process.argv[1]}`) await buildIsolate();
