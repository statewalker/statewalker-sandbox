// Builds the bundler Worker (src/bundler/program.ts) into src/bundler/program.gen.js:
//   { code, wasmSha256, esbuildVersion }
// `code` is one ES module that imports ./esbuild.wasm (given by the Agent when it loads the
// isolate); wasmSha256 pins the esbuild.wasm it needs; Node's builtin export names are recorded
// in it so bundles built there match bundles built on Node.
//   node scripts/build-bundler.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
import { builtinExportNames } from "../src/tools/bundle.ts";

const dir = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(`${dir}package.json`);
const wasmPath = require.resolve("esbuild-wasm/esbuild.wasm");
const esbuildVersion = require("esbuild-wasm/package.json").version;

export async function buildBundler({ quiet = false } = {}) {
  const out = await esbuild.build({
    entryPoints: [`${dir}src/bundler/program.ts`],
    bundle: true,
    format: "esm",
    platform: "neutral",
    mainFields: ["browser", "module", "main"],
    conditions: ["workerd", "worker", "browser"],
    external: ["cloudflare:workers", "./esbuild.wasm"],
    define: { __CAPFS_BUILTIN_NAMES__: JSON.stringify(await builtinExportNames()) },
    minify: true,
    write: false,
    logLevel: quiet ? "silent" : "warning",
  });
  const code = out.outputFiles[0].text;
  const wasmSha256 = createHash("sha256").update(readFileSync(wasmPath)).digest("hex");
  writeFileSync(
    `${dir}src/bundler/program.gen.js`,
    `// Generated by scripts/build-bundler.mjs from src/bundler/program.ts. Do not edit.\nexport default ${JSON.stringify({ code, wasmSha256, esbuildVersion })};\n`,
  );
  if (!quiet)
    console.log(
      `bundler: ${code.length} bytes, esbuild-wasm ${esbuildVersion}, wasm sha256 ${wasmSha256}`,
    );
  return { wasmPath, wasmSha256 };
}

if (import.meta.url === `file://${process.argv[1]}`) await buildBundler();
